import { compose } from '../core/doc';
import { ValidationError } from '../core/errors';
import { resampleRgba, type ResampleAlgorithm } from '../core/scale';
import type { Doc } from '../core/types';
import { bytesToDataUrl, encodePngRgba } from './png';

export type JsExportMode = 'canvas2d' | 'dataurl' | 'rgba';

export interface JsExportOptions {
  mode: JsExportMode;
  scale: number;
  algorithm: ResampleAlgorithm;
  includeHidden: boolean;
  varName: string;
}

function sanitizeIdentifier(raw: string): string {
  const cleaned = raw.replace(/[^a-zA-Z0-9_$]/g, '_').replace(/^(\d)/, '_$1');
  return cleaned.length > 0 ? cleaned : 'sprite';
}

function rgbaToHex(r: number, g: number, b: number, a: number): string {
  const h = (n: number) => n.toString(16).padStart(2, '0');
  return a === 255 ? `#${h(r)}${h(g)}${h(b)}` : `#${h(r)}${h(g)}${h(b)}${h(a)}`;
}

/** Generate clean, zero-dependency JavaScript ES module code for the selected sprite frames. */
export function exportSpriteJs(
  doc: Doc,
  frames: number[],
  opts: Partial<JsExportOptions> = {},
): string {
  if (frames.length === 0) throw new ValidationError('No frames selected for JavaScript export.');
  const mode: JsExportMode = opts.mode ?? 'canvas2d';
  const scale = Math.max(1, Math.min(16, Math.round(opts.scale ?? 1)));
  const algorithm: ResampleAlgorithm = opts.algorithm ?? 'nearest';
  const includeHidden = Boolean(opts.includeHidden);
  const name = sanitizeIdentifier(opts.varName ?? 'sprite');

  const outW = doc.w * scale;
  const outH = doc.h * scale;

  const renderedFrames = frames.map((f) => {
    const composed = compose(doc, f, { includeHidden });
    const data = scale === 1 ? composed : resampleRgba(composed, doc.w, doc.h, outW, outH, algorithm);
    return {
      data,
      duration: Math.max(20, doc.frames[f]?.duration ?? 100),
    };
  });

  if (mode === 'dataurl') {
    const urls = renderedFrames.map((rf) => bytesToDataUrl(encodePngRgba(rf.data, outW, outH)));
    const durations = renderedFrames.map((rf) => rf.duration);
    return [
      `// Generated by Tintbox (${outW}x${outH}, ${renderedFrames.length} frame${renderedFrames.length === 1 ? '' : 's'})`,
      `export const ${name} = {`,
      `  width: ${outW},`,
      `  height: ${outH},`,
      `  durations: ${JSON.stringify(durations)},`,
      `  frames: ${JSON.stringify(urls, null, 2).replace(/\n/g, '\n  ')},`,
      `};`,
      ``,
      `export function load${name[0].toUpperCase()}${name.slice(1)}Images() {`,
      `  return Promise.all(${name}.frames.map((src) => new Promise((resolve, reject) => {`,
      `    const img = new Image();`,
      `    img.onload = () => resolve(img);`,
      `    img.onerror = reject;`,
      `    img.src = src;`,
      `  })));`,
      `}`,
      ``,
    ].join('\n');
  }

  if (mode === 'rgba') {
    const frameArrays = renderedFrames.map((rf) => `new Uint8ClampedArray([${Array.from(rf.data).join(',')}])`);
    const durations = renderedFrames.map((rf) => rf.duration);
    return [
      `// Generated by Tintbox (${outW}x${outH} straight RGBA)`,
      `export const ${name} = {`,
      `  width: ${outW},`,
      `  height: ${outH},`,
      `  durations: ${JSON.stringify(durations)},`,
      `  frames: [`,
      ...frameArrays.map((a) => `    ${a},`),
      `  ],`,
      `};`,
      ``,
      `export function toImageData(frameIndex = 0) {`,
      `  const data = ${name}.frames[frameIndex] ?? ${name}.frames[0];`,
      `  return new ImageData(new Uint8ClampedArray(data), ${name}.width, ${name}.height);`,
      `}`,
      ``,
    ].join('\n');
  }

  // Default: compact indexed-palette Canvas 2D pixel renderer
  const palette: string[] = ['']; // index 0 = transparent
  const colorMap = new Map<string, number>();
  const encodedFrames: number[][][] = []; // per-frame rows of palette indices (RLE runs [colorIdx, count])

  for (const rf of renderedFrames) {
    const runs: number[][] = [];
    const d = rf.data;
    for (let y = 0; y < outH; y++) {
      const rowRuns: number[] = [];
      let curIdx = -1;
      let curLen = 0;
      for (let x = 0; x < outW; x++) {
        const o = (y * outW + x) * 4;
        let ci = 0;
        if (d[o + 3] > 0) {
          const hex = rgbaToHex(d[o], d[o + 1], d[o + 2], d[o + 3]);
          let found = colorMap.get(hex);
          if (found === undefined) {
            found = palette.length;
            palette.push(hex);
            colorMap.set(hex, found);
          }
          ci = found;
        }
        if (ci === curIdx) {
          curLen++;
        } else {
          if (curLen > 0) rowRuns.push(curIdx, curLen);
          curIdx = ci;
          curLen = 1;
        }
      }
      if (curLen > 0) rowRuns.push(curIdx, curLen);
      runs.push(rowRuns);
    }
    encodedFrames.push(runs);
  }

  const durations = renderedFrames.map((rf) => rf.duration);
  const fnCap = `${name[0].toUpperCase()}${name.slice(1)}`;

  return [
    `// Generated by Tintbox (${outW}x${outH}, ${renderedFrames.length} frame${renderedFrames.length === 1 ? '' : 's'})`,
    `export const ${name} = {`,
    `  width: ${outW},`,
    `  height: ${outH},`,
    `  durations: ${JSON.stringify(durations)},`,
    `  palette: ${JSON.stringify(palette)},`,
    `  // Each row is RLE pairs [paletteIndex, runLength]; index 0 is transparent`,
    `  frames: ${JSON.stringify(encodedFrames)},`,
    `};`,
    ``,
    `export function draw${fnCap}(ctx, x = 0, y = 0, pixelScale = 1, frameIndex = 0) {`,
    `  const rows = ${name}.frames[frameIndex] ?? ${name}.frames[0];`,
    `  for (let row = 0; row < rows.length; row++) {`,
    `    const runs = rows[row];`,
    `    let col = 0;`,
    `    for (let i = 0; i < runs.length; i += 2) {`,
    `      const ci = runs[i];`,
    `      const len = runs[i + 1];`,
    `      if (ci !== 0) {`,
    `        ctx.fillStyle = ${name}.palette[ci];`,
    `        ctx.fillRect(x + col * pixelScale, y + row * pixelScale, len * pixelScale, pixelScale);`,
    `      }`,
    `      col += len;`,
    `    }`,
    `  }`,
    `}`,
    ``,
  ].join('\n');
}
